/// Auxiliary overlap integral moment for multipole charge separations.
/// Equation (7) of Thiel & Voityuk (1996) / OpenMOPAC `aijl` (`mndod.F90` lines 2146-2157).
pub fn aijl(z1: f64, z2: f64, n1: usize, n2: usize, l: usize, fx: &[f64; 31]) -> f64 {
    let zz = z1 + z2 + 1.0e-20;
    fx[n1 + n2 + l + 1] / (fx[2 * n1 + 1] * fx[2 * n2 + 1]).sqrt()
        * (2.0 * z1 / zz).powi(n1 as i32)
        * (2.0 * z1 / zz).sqrt()
        * (2.0 * z2 / zz).powi(n2 as i32)
        * (2.0 * z2 / zz).sqrt()
        * (2.0f64.powi(l as i32) / zz.powi(l as i32))
}

/// Calculate multipole moments aij for an element.
/// Direct port of OpenMOPAC `aijm` (`mndod.F90` lines 2097-2142).
pub fn aijm(ni: u8, zs: f64, zp: f64, zd: f64, has_d: bool, fx: &[f64; 31]) -> [f64; 7] {
    let mut aij = [0.0f64; 7];
    if ni < 3 {
        return aij;
    }
    let zz = zs * zp;
    if zz < 0.01 {
        return aij;
    }
    let nsp = III[ni as usize];
    aij[2] = aijl(zs, zp, nsp, nsp, 1, fx);
    aij[3] = aijl(zp, zp, nsp, nsp, 2, fx);
    if has_d {
        let nd = IIID[ni as usize];
        aij[4] = aijl(zs, zd, nsp, nd, 2, fx);
        aij[5] = aijl(zp, zd, nsp, nd, 1, fx);
        aij[6] = aijl(zd, zd, nd, nd, 2, fx);
    }
    aij
}

/// Determine additive terms rho = poij for two-center two-electron integrals.
/// Golden-section root finder reproducing one-center terms.
/// Direct port of OpenMOPAC `poij` (`mndod.F90` lines 165-242).
pub fn poij(l: usize, d: f64, fg: f64) -> f64 {
    let ev = EV_HARTREE;
    if l == 0 {
        return 0.5 * ev / fg;
    }
    let dsq = d * d;
    let ev4 = ev * 0.25;
    let ev8 = ev / 8.0;
    let mut a1 = 0.1;
    let mut a2 = 5.0;
    const EPSIL: f64 = 1.0e-8;
    const G1: f64 = 0.382;
    const G2: f64 = 0.618;

    if l == 1 {
        for _ in 0..100 {
            let delta = a2 - a1;
            if delta < EPSIL {
                break;
            }
            let y1 = a1 + delta * G1;
            let y2 = a1 + delta * G2;
            let f1_val = ev4 * (1.0 / y1 - 1.0 / (y1 * y1 + dsq).sqrt()) - fg;
            let f2_val = ev4 * (1.0 / y2 - 1.0 / (y2 * y2 + dsq).sqrt()) - fg;
            if f1_val * f1_val < f2_val * f2_val {
                a2 = y2;
            } else {
                a1 = y1;
            }
        }
    } else if l == 2 {
        for _ in 0..100 {
            let delta = a2 - a1;
            if delta < EPSIL {
                break;
            }
            let y1 = a1 + delta * G1;
            let y2 = a1 + delta * G2;
            let f1_val = ev8
                * (1.0 / y1 - 2.0 / (y1 * y1 + dsq * 0.5).sqrt() + 1.0 / (y1 * y1 + dsq).sqrt())
                - fg;
            let f2_val = ev8
                * (1.0 / y2 - 2.0 / (y2 * y2 + dsq * 0.5).sqrt() + 1.0 / (y2 * y2 + dsq).sqrt())
                - fg;
            if f1_val * f1_val < f2_val * f2_val {
                a2 = y2;
            } else {
                a1 = y1;
            }
        }
    }
    (a1 + a2) * 0.5
}

/// Calculate charge separations ddp and additive terms po.
/// Direct port of OpenMOPAC `ddpo` (`mndod.F90` lines 2287-2363).
pub fn ddpo(
    ni: u8,
    gss: f64,
    hsp: f64,
    gpp: f64,
    gp2: f64,
    has_d: bool,
    aij: &[f64; 7],
    repd: &[f64; 53],
    ddp: &mut [f64; 7],
    po: &mut [f64; 10],
) {
    if gss > 0.1 {
        po[1] = poij(0, 1.0, gss);
    }
    if ni >= 3 {
        // SP
        let d_sp = aij[2] / 12.0f64.sqrt();
        ddp[2] = d_sp;
        po[2] = poij(1, d_sp, hsp);

        // PP
        po[7] = po[1];
        let d_pp = (aij[3] * 0.1).sqrt();
        let fg_pp = 0.5 * (gpp - gp2);
        ddp[3] = d_pp;
        po[3] = poij(2, d_pp, fg_pp);

        if has_d {
            // SD
            let da = (1.0 / 60.0f64).sqrt();
            let d_sd = (aij[4] * da).sqrt();
            let fg_sd = repd[19];
            ddp[4] = d_sd;
            po[4] = poij(2, d_sd, fg_sd);

            // PD
            let d_pd = aij[5] / 20.0f64.sqrt();
            let fg_pd = repd[23] - 1.8 * repd[35];
            ddp[5] = d_pd;
            po[5] = poij(1, d_pd, fg_pd);

            // DD
            let fg_dd = 0.2 * (repd[29] + 2.0 * repd[30] + 2.0 * repd[31]);
            if fg_dd > 1.0e-5 {
                po[8] = poij(0, 1.0, fg_dd);
            } else {
                po[8] = 1.0e5;
            }
            let d_dd = (aij[6] / 14.0).sqrt();
            let fg_dd2 = repd[44] - (20.0 / 35.0) * repd[52];
            ddp[6] = d_dd;
            po[6] = poij(2, d_dd, fg_dd2);
        }
    }
}

/// Complete set of precomputed parameters for an element with d-orbitals.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct DElementParams {
    pub z: u8,
    pub repd: [f64; 53],
    pub ddp: [f64; 7],
    pub po: [f64; 10],
}

/// Compute derived parameters for an element with d-orbitals.
pub fn compute_d_element_params(
    z: u8,
    zs: f64,
    zp: f64,
    zd: f64,
    gss: f64,
    _gsp: f64,
    gpp: f64,
    gp2: f64,
    hsp: f64,
    zsn: f64,
    zpn: f64,
    zdn: f64,
    f0sd_override: f64,
    g2sd_override: f64,
    pocord: f64,
) -> DElementParams {
    let (fx, b) = init_fbx();
    let (r066, r266, r466, r016, r244, r036, r236, r155, r355, r125, r234, r246) =
        scprm(z, zsn, zpn, zdn, &fx, &b);

    let mut repd = [0.0f64; 53];
    inighd(
        r016,
        r066,
        r244,
        r266,
        r466,
        r036,
        r236,
        r155,
        r355,
        r125,
        r234,
        r246,
        f0sd_override,
        g2sd_override,
        &mut repd,
    );

    let aij = aijm(z, zs, zp, zd, true, &fx);
    let mut ddp = [0.0f64; 7];
    let mut po = [0.0f64; 10];
    ddpo(z, gss, hsp, gpp, gp2, true, &aij, &repd, &mut ddp, &mut po);

    po[9] = po[1];
    if pocord > 1.0e-5 {
        po[9] = pocord;
    }

    DElementParams { z, repd, ddp, po }
}

/// Fill square matrix of one-center two-electron integrals (wstore).
/// Direct port of OpenMOPAC `wstore` (`mndod.F90` lines 2027-2095).
pub fn wstore(
    _ni: u8,
    norb: usize,
    gss: f64,
    gsp: f64,
    gpp: f64,
    gp2: f64,
    hsp: f64,
    repd: Option<&[f64; 53]>,
    w: &mut [f64],
) {
    let ilim = (norb * (norb + 1)) / 2;
    w[..ilim * ilim].fill(0.0);

    let idx = |i: usize, j: usize| -> usize { (i - 1) * ilim + (j - 1) };

    w[idx(1, 1)] = gss;
    if norb >= 4 {
        let ipx = 3;
        let ipy = 6;
        let ipz = 10;
        w[idx(ipx, 1)] = gsp;
        w[idx(ipy, 1)] = gsp;
        w[idx(ipz, 1)] = gsp;
        w[idx(1, ipx)] = gsp;
        w[idx(1, ipy)] = gsp;
        w[idx(1, ipz)] = gsp;
        w[idx(ipx, ipx)] = gpp;
        w[idx(ipy, ipy)] = gpp;
        w[idx(ipz, ipz)] = gpp;
        w[idx(ipy, ipx)] = gp2;
        w[idx(ipz, ipx)] = gp2;
        w[idx(ipz, ipy)] = gp2;
        w[idx(ipx, ipy)] = gp2;
        w[idx(ipx, ipz)] = gp2;
        w[idx(ipy, ipz)] = gp2;
        w[idx(2, 2)] = hsp;
        w[idx(4, 4)] = hsp;
        w[idx(7, 7)] = hsp;
        w[idx(5, 5)] = 0.5 * (gpp - gp2);
        w[idx(8, 8)] = 0.5 * (gpp - gp2);
        w[idx(9, 9)] = 0.5 * (gpp - gp2);

        if ilim > 10 {
            if let Some(rep) = repd {
                for i in 0..243 {
                    let ij = INTIJ[i];
                    let kl = INTKL[i];
                    let int_rep = INTREP[i];
                    w[idx(ij, kl)] = rep[int_rep];
                }
            }
        }
    }
}

