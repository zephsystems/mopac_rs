/// 3D Spatial Frame Rotation Engine for p- and d-orbitals.
///
/// Implements exact SO(3) representation transformations matching OpenMOPAC `rotmat.F90`.
#[derive(Debug, Clone, Copy)]
pub struct DOrbitalRotation3D {
    pub r_bohr: f64,
    /// 3x3 rotation matrix for p orbitals (px, py, pz)
    pub p: [[f64; 3]; 3],
    /// 5x5 rotation matrix for d orbitals (dx2-y2, dxz, dz2, dyz, dxy)
    pub d: [[f64; 5]; 5],
    /// Tensor product S-P: sp(3, 3)
    pub sp: [[f64; 3]; 3],
    /// Tensor product P-P: pp(6, 3, 3)
    pub pp: [[[f64; 3]; 3]; 6],
    /// Tensor product S-D: sd(5, 5)
    pub sd: [[f64; 5]; 5],
    /// Tensor product D-P: dp(15, 5, 3)
    pub dp: [[[f64; 3]; 5]; 15],
    /// Tensor product D-D: d_d(15, 5, 5)
    pub d_d: [[[f64; 5]; 5]; 15],
}

impl DOrbitalRotation3D {
    /// Construct rotation from displacement vector pointing from atom A to atom B.
    pub fn new(dx_ang: f64, dy_ang: f64, dz_ang: f64, r_ang: f64) -> Self {
        let r_bohr = r_ang / A0_BOHR;
        let small = 1.0e-7;
        let pt5sq3 = 3.0f64.sqrt() * 0.5;

        let b = dx_ang * dx_ang + dy_ang * dy_ang;
        let sqb = b.sqrt();
        let sb = sqb / r_ang;

        let (ca, sa, cb) = if sb > small {
            (dx_ang / sqb, dy_ang / sqb, dz_ang / r_ang)
        } else {
            let (ca_val, cb_val) = if dz_ang < 0.0 {
                (-1.0, -1.0)
            } else if dz_ang > 0.0 {
                (1.0, 1.0)
            } else {
                (0.0, 0.0)
            };
            (ca_val, 0.0, cb_val)
        };

        // p(3, 3) matrix
        let mut p = [[0.0f64; 3]; 3];
        p[0][0] = ca * sb;
        p[1][0] = ca * cb;
        p[2][0] = -sa;
        p[0][1] = sa * sb;
        p[1][1] = sa * cb;
        p[2][1] = ca;
        p[0][2] = cb;
        p[1][2] = -sb;
        p[2][2] = 0.0;

        let c2a = 2.0 * ca * ca - 1.0;
        let c2b = 2.0 * cb * cb - 1.0;
        let s2a = 2.0 * sa * ca;
        let s2b = 2.0 * sb * cb;

        // d(5, 5) matrix
        let mut d = [[0.0f64; 5]; 5];
        d[0][0] = pt5sq3 * c2a * sb * sb;
        d[1][0] = 0.5 * c2a * s2b;
        d[2][0] = -s2a * sb;
        d[3][0] = c2a * (cb * cb + 0.5 * sb * sb);
        d[4][0] = -s2a * cb;

        d[0][1] = pt5sq3 * ca * s2b;
        d[1][1] = ca * c2b;
        d[2][1] = -sa * cb;
        d[3][1] = -0.5 * ca * s2b;
        d[4][1] = sa * sb;

        d[0][2] = cb * cb - 0.5 * sb * sb;
        d[1][2] = -pt5sq3 * s2b;
        d[2][2] = 0.0;
        d[3][2] = pt5sq3 * sb * sb;
        d[4][2] = 0.0;

        d[0][3] = pt5sq3 * sa * s2b;
        d[1][3] = sa * c2b;
        d[2][3] = ca * cb;
        d[3][3] = -0.5 * sa * s2b;
        d[4][3] = -ca * sb;

        d[0][4] = pt5sq3 * s2a * sb * sb;
        d[1][4] = 0.5 * s2a * s2b;
        d[2][4] = c2a * sb;
        d[3][4] = s2a * (cb * cb + 0.5 * sb * sb);
        d[4][4] = c2a * cb;

        // sp = p
        let sp = p;

        // pp(6, 3, 3)
        let mut pp = [[[0.0f64; 3]; 3]; 6];
        for k in 0..3 {
            pp[0][k][k] = p[k][0] * p[k][0];
            pp[1][k][k] = p[k][1] * p[k][1];
            pp[2][k][k] = p[k][2] * p[k][2];
            pp[3][k][k] = p[k][0] * p[k][1];
            pp[4][k][k] = p[k][0] * p[k][2];
            pp[5][k][k] = p[k][1] * p[k][2];
            for prev in 0..k {
                pp[0][k][prev] = 2.0 * p[k][0] * p[prev][0];
                pp[1][k][prev] = 2.0 * p[k][1] * p[prev][1];
                pp[2][k][prev] = 2.0 * p[k][2] * p[prev][2];
                pp[3][k][prev] = p[k][0] * p[prev][1] + p[k][1] * p[prev][0];
                pp[4][k][prev] = p[k][0] * p[prev][2] + p[k][2] * p[prev][0];
                pp[5][k][prev] = p[k][1] * p[prev][2] + p[k][2] * p[prev][1];
            }
        }

        // sd = d
        let sd = d;

        // dp(15, 5, 3)
        let mut dp = [[[0.0f64; 3]; 5]; 15];
        for k in 0..5 {
            for col in 0..3 {
                dp[0][k][col] = d[k][0] * p[col][0];
                dp[1][k][col] = d[k][0] * p[col][1];
                dp[2][k][col] = d[k][0] * p[col][2];
                dp[3][k][col] = d[k][1] * p[col][0];
                dp[4][k][col] = d[k][1] * p[col][1];
                dp[5][k][col] = d[k][1] * p[col][2];
                dp[6][k][col] = d[k][2] * p[col][0];
                dp[7][k][col] = d[k][2] * p[col][1];
                dp[8][k][col] = d[k][2] * p[col][2];
                dp[9][k][col] = d[k][3] * p[col][0];
                dp[10][k][col] = d[k][3] * p[col][1];
                dp[11][k][col] = d[k][3] * p[col][2];
                dp[12][k][col] = d[k][4] * p[col][0];
                dp[13][k][col] = d[k][4] * p[col][1];
                dp[14][k][col] = d[k][4] * p[col][2];
            }
        }

        // d_d(15, 5, 5)
        let mut d_d = [[[0.0f64; 5]; 5]; 15];
        for k in 0..5 {
            d_d[0][k][k] = d[k][0] * d[k][0];
            d_d[1][k][k] = d[k][1] * d[k][1];
            d_d[2][k][k] = d[k][2] * d[k][2];
            d_d[3][k][k] = d[k][3] * d[k][3];
            d_d[4][k][k] = d[k][4] * d[k][4];
            d_d[5][k][k] = d[k][0] * d[k][1];
            d_d[6][k][k] = d[k][0] * d[k][2];
            d_d[7][k][k] = d[k][1] * d[k][2];
            d_d[8][k][k] = d[k][0] * d[k][3];
            d_d[9][k][k] = d[k][1] * d[k][3];
            d_d[10][k][k] = d[k][2] * d[k][3];
            d_d[11][k][k] = d[k][0] * d[k][4];
            d_d[12][k][k] = d[k][1] * d[k][4];
            d_d[13][k][k] = d[k][2] * d[k][4];
            d_d[14][k][k] = d[k][3] * d[k][4];
            for prev in 0..k {
                d_d[0][k][prev] = 2.0 * d[k][0] * d[prev][0];
                d_d[1][k][prev] = 2.0 * d[k][1] * d[prev][1];
                d_d[2][k][prev] = 2.0 * d[k][2] * d[prev][2];
                d_d[3][k][prev] = 2.0 * d[k][3] * d[prev][3];
                d_d[4][k][prev] = 2.0 * d[k][4] * d[prev][4];
                d_d[5][k][prev] = d[k][0] * d[prev][1] + d[k][1] * d[prev][0];
                d_d[6][k][prev] = d[k][0] * d[prev][2] + d[k][2] * d[prev][0];
                d_d[7][k][prev] = d[k][1] * d[prev][2] + d[k][2] * d[prev][1];
                d_d[8][k][prev] = d[k][0] * d[prev][3] + d[k][3] * d[prev][0];
                d_d[9][k][prev] = d[k][1] * d[prev][3] + d[k][3] * d[prev][1];
                d_d[10][k][prev] = d[k][2] * d[prev][3] + d[k][3] * d[prev][2];
                d_d[11][k][prev] = d[k][0] * d[prev][4] + d[k][4] * d[prev][0];
                d_d[12][k][prev] = d[k][1] * d[prev][4] + d[k][4] * d[prev][1];
                d_d[13][k][prev] = d[k][2] * d[prev][4] + d[k][4] * d[prev][2];
                d_d[14][k][prev] = d[k][3] * d[prev][4] + d[k][4] * d[prev][3];
            }
        }

        Self {
            r_bohr,
            p,
            d,
            sp,
            pp,
            sd,
            dp,
            d_d,
        }
    }

    /// Check strict SO(3) orthonormality of p (3x3) and d (5x5) rotation matrices.
    /// Returns (||P P^T - I_3||_inf, ||D D^T - I_5||_inf).
    pub fn check_orthonormality(&self) -> (f64, f64) {
        let mut err_p = 0.0f64;
        for i in 0..3 {
            for j in 0..3 {
                let mut dot = 0.0;
                for k in 0..3 {
                    dot += self.p[i][k] * self.p[j][k];
                }
                let target = if i == j { 1.0 } else { 0.0 };
                err_p = err_p.max((dot - target).abs());
            }
        }

        let mut err_d = 0.0f64;
        for i in 0..5 {
            for j in 0..5 {
                let mut dot = 0.0;
                for k in 0..5 {
                    dot += self.d[i][k] * self.d[j][k];
                }
                let target = if i == j { 1.0 } else { 0.0 };
                err_d = err_d.max((dot - target).abs());
            }
        }

        (err_p, err_d)
    }

    /// Compute Casimir invariant preservation: ||D v||^2 - ||v||^2 for any 5D spherical vector.
    pub fn casimir_invariance(&self, v: &[f64; 5]) -> f64 {
        let mut norm_in_sq = 0.0;
        for &x in v {
            norm_in_sq += x * x;
        }

        let mut norm_out_sq = 0.0;
        for i in 0..5 {
            let mut dot = 0.0;
            for j in 0..5 {
                dot += self.d[i][j] * v[j];
            }
            norm_out_sq += dot * dot;
        }

        (norm_out_sq - norm_in_sq).abs()
    }
}

/// Evaluation of the two point-charge interaction configurations (MNDO/d).
/// Direct port of OpenMOPAC `charg` (`mndod.F90` lines 2160-2284).
pub fn charg(r: f64, l1: usize, l2: usize, m: usize, da: f64, db: f64, add: f64) -> f64 {
    let mut val = 0.0f64;
    if l1 == 0 && l2 == 0 {
        val = 1.0 / (r * r + add).sqrt();
    } else if l1 == 1 && l2 == 0 {
        val = (-1.0 / ((r + da) * (r + da) + add).sqrt()
            + 1.0 / ((r - da) * (r - da) + add).sqrt())
            * 0.5;
    } else if l1 == 0 && l2 == 1 {
        val = (1.0 / ((r + db) * (r + db) + add).sqrt() - 1.0 / ((r - db) * (r - db) + add).sqrt())
            * 0.5;
    } else if l1 == 1 && l2 == 1 && m == 0 {
        let dzdz = 1.0 / ((r + da - db) * (r + da - db) + add).sqrt()
            + 1.0 / ((r - da + db) * (r - da + db) + add).sqrt()
            - 1.0 / ((r - da - db) * (r - da - db) + add).sqrt()
            - 1.0 / ((r + da + db) * (r + da + db) + add).sqrt();
        val = dzdz * 0.25;
    } else if l1 == 1 && l2 == 1 && m == 1 {
        let dxdx = 2.0 / (r * r + (da - db) * (da - db) + add).sqrt()
            - 2.0 / (r * r + (da + db) * (da + db) + add).sqrt();
        val = dxdx * 0.25;
    } else if l1 == 0 && l2 == 2 {
        let qqzz = 1.0 / ((r - db) * (r - db) + add).sqrt() - 2.0 / (r * r + db * db + add).sqrt()
            + 1.0 / ((r + db) * (r + db) + add).sqrt();
        val = qqzz * 0.25;
    } else if l1 == 2 && l2 == 0 {
        let qzzq = 1.0 / ((r - da) * (r - da) + add).sqrt() - 2.0 / (r * r + da * da + add).sqrt()
            + 1.0 / ((r + da) * (r + da) + add).sqrt();
        val = qzzq * 0.25;
    } else if l1 == 1 && l2 == 2 && m == 0 {
        let dzqzz = 1.0 / ((r - da - db) * (r - da - db) + add).sqrt()
            - 2.0 / ((r - da) * (r - da) + db * db + add).sqrt()
            + 1.0 / ((r + db - da) * (r + db - da) + add).sqrt()
            - 1.0 / ((r - db + da) * (r - db + da) + add).sqrt()
            + 2.0 / ((r + da) * (r + da) + db * db + add).sqrt()
            - 1.0 / ((r + da + db) * (r + da + db) + add).sqrt();
        val = dzqzz * 0.125;
    } else if l1 == 2 && l2 == 1 && m == 0 {
        let qzzdz = -1.0 / ((r - da - db) * (r - da - db) + add).sqrt()
            + 2.0 / ((r - db) * (r - db) + da * da + add).sqrt()
            - 1.0 / ((r + da - db) * (r + da - db) + add).sqrt()
            + 1.0 / ((r - da + db) * (r - da + db) + add).sqrt()
            - 2.0 / ((r + db) * (r + db) + da * da + add).sqrt()
            + 1.0 / ((r + da + db) * (r + da + db) + add).sqrt();
        val = qzzdz * 0.125;
    } else if l1 == 2 && l2 == 2 && m == 0 {
        let zzzz = 1.0 / ((r - da - db) * (r - da - db) + add).sqrt()
            + 1.0 / ((r + da + db) * (r + da + db) + add).sqrt()
            + 1.0 / ((r - da + db) * (r - da + db) + add).sqrt()
            + 1.0 / ((r + da - db) * (r + da - db) + add).sqrt()
            - 2.0 / ((r - da) * (r - da) + db * db + add).sqrt()
            - 2.0 / ((r - db) * (r - db) + da * da + add).sqrt()
            - 2.0 / ((r + da) * (r + da) + db * db + add).sqrt()
            - 2.0 / ((r + db) * (r + db) + da * da + add).sqrt()
            + 2.0 / (r * r + (da - db) * (da - db) + add).sqrt()
            + 2.0 / (r * r + (da + db) * (da + db) + add).sqrt();
        let xyxy = 4.0 / (r * r + (da - db) * (da - db) + add).sqrt()
            + 4.0 / (r * r + (da + db) * (da + db) + add).sqrt()
            - 8.0 / (r * r + da * da + db * db + add).sqrt();
        val = zzzz * 0.0625 - xyxy * 0.015625;
    } else if l1 == 1 && l2 == 2 && m == 1 {
        let ab = db / 2.0f64.sqrt();
        let dxqxz = -2.0 / ((r - ab) * (r - ab) + (da - ab) * (da - ab) + add).sqrt()
            + 2.0 / ((r + ab) * (r + ab) + (da - ab) * (da - ab) + add).sqrt()
            + 2.0 / ((r - ab) * (r - ab) + (da + ab) * (da + ab) + add).sqrt()
            - 2.0 / ((r + ab) * (r + ab) + (da + ab) * (da + ab) + add).sqrt();
        val = dxqxz * 0.125;
    } else if l1 == 2 && l2 == 1 && m == 1 {
        let aa = da / 2.0f64.sqrt();
        let qxzdx = -2.0 / ((r + aa) * (r + aa) + (aa - db) * (aa - db) + add).sqrt()
            + 2.0 / ((r - aa) * (r - aa) + (aa - db) * (aa - db) + add).sqrt()
            + 2.0 / ((r + aa) * (r + aa) + (aa + db) * (aa + db) + add).sqrt()
            - 2.0 / ((r - aa) * (r - aa) + (aa + db) * (aa + db) + add).sqrt();
        val = qxzdx * 0.125;
    } else if l1 == 2 && l2 == 2 && m == 1 {
        let aa = da / 2.0f64.sqrt();
        let ab = db / 2.0f64.sqrt();
        let qxzqxz = 2.0 / ((r + aa - ab) * (r + aa - ab) + (aa - ab) * (aa - ab) + add).sqrt()
            - 2.0 / ((r + aa + ab) * (r + aa + ab) + (aa - ab) * (aa - ab) + add).sqrt()
            - 2.0 / ((r - aa - ab) * (r - aa - ab) + (aa - ab) * (aa - ab) + add).sqrt()
            + 2.0 / ((r - aa + ab) * (r - aa + ab) + (aa - ab) * (aa - ab) + add).sqrt()
            - 2.0 / ((r + aa - ab) * (r + aa - ab) + (aa + ab) * (aa + ab) + add).sqrt()
            + 2.0 / ((r + aa + ab) * (r + aa + ab) + (aa + ab) * (aa + ab) + add).sqrt()
            + 2.0 / ((r - aa - ab) * (r - aa - ab) + (aa + ab) * (aa + ab) + add).sqrt()
            - 2.0 / ((r - aa + ab) * (r - aa + ab) + (aa + ab) * (aa + ab) + add).sqrt();
        val = qxzqxz * 0.0625;
    } else if l1 == 2 && l2 == 2 && m == 2 {
        let xyxy = 4.0 / (r * r + (da - db) * (da - db) + add).sqrt()
            + 4.0 / (r * r + (da + db) * (da + db) + add).sqrt()
            - 8.0 / (r * r + da * da + db * db + add).sqrt();
        val = xyxy * 0.0625;
    }
    val
}

/// Compute diatomic multipole interaction element in local frame.
/// Direct port of OpenMOPAC `rijkl` (`mndod.F90` lines 1000-1093).
pub fn rijkl(
    po_a: &[f64; 10],
    ddp_a: &[f64; 7],
    po_b: &[f64; 10],
    ddp_b: &[f64; 7],
    ij_pair: usize, // 1-based index 1..45
    kl_pair: usize, // 1-based index 1..45
    li: usize,
    lj: usize,
    lk: usize,
    ll: usize,
    ic: usize,
    r_bohr: f64,
) -> f64 {
    let l1min = (li as isize - lj as isize).unsigned_abs().min(2);
    let l1max = (li + lj).min(2);
    let lij = INDX[li][lj]; // 1-based pair index: 1..6

    let l2min = (lk as isize - ll as isize).unsigned_abs().min(2);
    let l2max = (lk + ll).min(2);
    let lkl = INDX[lk][ll]; // 1-based pair index: 1..6

    let mut sum = 0.0f64;

    for l1 in l1min..=l1max {
        let (dij, pij) = if l1 == 0 {
            let p = match lij {
                1 => {
                    if ic == 1 {
                        po_a[9]
                    } else {
                        po_a[1]
                    }
                }
                3 => po_a[7],
                6 => po_a[8],
                _ => po_a[1],
            };
            (0.0, p)
        } else {
            (ddp_a[lij], po_a[lij])
        };

        for l2 in l2min..=l2max {
            let (dkl, pkl) = if l2 == 0 {
                let p = match lkl {
                    1 => {
                        if ic == 2 {
                            po_b[9]
                        } else {
                            po_b[1]
                        }
                    }
                    3 => po_b[7],
                    6 => po_b[8],
                    _ => po_b[1],
                };
                (0.0, p)
            } else {
                (ddp_b[lkl], po_b[lkl])
            };

            let add = (pij + pkl) * (pij + pkl);
            let lmin = l1.min(l2);
            let mut s1 = 0.0f64;

            for m in -(lmin as isize)..=(lmin as isize) {
                let m_idx = (m + 2) as usize;
                let ccc = CH[ij_pair - 1][l1][m_idx] * CH[kl_pair - 1][l2][m_idx];
                if ccc.abs() < 1e-15 {
                    continue;
                }
                let mm = m.unsigned_abs();
                s1 += charg(r_bohr, l1, l2, mm, dij, dkl, add) * ccc;
            }
            sum += s1;
        }
    }
    sum
}

