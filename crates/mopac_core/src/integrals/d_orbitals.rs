/// Compute 491 local-frame two-center two-electron repulsion integrals.
/// Direct port of OpenMOPAC `reppd2` (`mndod.F90` lines 846-997).
pub fn compute_reppd2(
    norb_a: usize,
    norb_b: usize,
    r_bohr: f64,
    ri: &[f64; 22],
    po_a: &[f64; 10],
    ddp_a: &[f64; 7],
    po_b: &[f64; 10],
    ddp_b: &[f64; 7],
    tore_a: f64,
    tore_b: f64,
    rep: &mut [f64; 492],
    core: &mut [[f64; 2]; 10],
    feather: bool,
) {
    let ev = EV_HARTREE;
    for (m, &pos) in IPOS.iter().enumerate() {
        rep[m + 1] = ri[pos - 1];
    }

    let has_d_a = norb_a >= 9;
    let has_d_b = norb_b >= 9;

    if has_d_a || has_d_b {
        let lasti = norb_a;
        let lastk = norb_b;

        for i in 1..=lasti {
            let li = LORB[i - 1];
            for j in 1..=i {
                let lj = LORB[j - 1];
                let ij = INDEXD[i - 1][j - 1];
                let coul = i == j;

                for k in 1..=lastk {
                    let lk = LORB[k - 1];
                    for l in 1..=k {
                        let ll = LORB[l - 1];
                        let kl = INDEXD[k - 1][l - 1];

                        let numb = IND2[ij - 1][kl - 1];
                        if numb <= 34 || numb > 491 {
                            continue;
                        }

                        let nold = ISYM[numb];
                        if nold >= 35 {
                            rep[numb] = rep[nold as usize];
                        } else if nold <= -35 {
                            rep[numb] = -rep[(-nold) as usize];
                        } else if nold == 0 {
                            let mut val =
                                rijkl(po_a, ddp_a, po_b, ddp_b, ij, kl, li, lj, lk, ll, 0, r_bohr)
                                    * ev;
                            if feather {
                                let r_angstrom = r_bohr * A0_BOHR;
                                let const_val = if r_angstrom < 7.0 {
                                    let dr = r_angstrom - 7.0;
                                    1.0 - (-dr * dr * 0.22).exp()
                                } else {
                                    0.0
                                };
                                let point =
                                    crate::constants::codata2018::EV_ANGSTROM_FACTOR / r_angstrom;
                                let coulomb = coul && k == l;
                                if coulomb {
                                    val = val * const_val + (1.0 - const_val) * point;
                                } else {
                                    val *= const_val;
                                }
                            }
                            rep[numb] = val;
                        }
                    }
                }
            }
        }

        for c in 4..10 {
            core[c][0] = 0.0;
            core[c][1] = 0.0;
        }

        if has_d_b {
            let ij = INDEXD[0][0]; // (s, s) on center A
                                   // <S S | D S>
            let mut kl = INDEXD[4][0];
            core[4][1] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, ij, kl, 0, 0, 2, 0, 1, r_bohr) * ev * tore_a;
            // <S S | D P>
            kl = INDEXD[4][1];
            core[5][1] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, ij, kl, 0, 0, 2, 1, 1, r_bohr) * ev * tore_a;
            // <S S | D D>
            kl = INDEXD[4][4];
            core[6][1] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, ij, kl, 0, 0, 2, 2, 1, r_bohr) * ev * tore_a;
            // <S S | D+ P+>
            kl = INDEXD[5][2];
            core[7][1] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, ij, kl, 0, 0, 2, 1, 1, r_bohr) * ev * tore_a;
            // <S S | D+ D+>
            kl = INDEXD[5][5];
            core[8][1] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, ij, kl, 0, 0, 2, 2, 1, r_bohr) * ev * tore_a;
            // <S S | D# D#>
            kl = INDEXD[7][7];
            core[9][1] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, ij, kl, 0, 0, 2, 2, 1, r_bohr) * ev * tore_a;
        }

        if has_d_a {
            let ij = INDEXD[0][0]; // (s, s) on center B
                                   // <D S | S S>
            let mut kl = INDEXD[4][0];
            core[4][0] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, kl, ij, 2, 0, 0, 0, 2, r_bohr) * ev * tore_b;
            // <D P | S S>
            kl = INDEXD[4][1];
            core[5][0] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, kl, ij, 2, 1, 0, 0, 2, r_bohr) * ev * tore_b;
            // <D D | S S>
            kl = INDEXD[4][4];
            core[6][0] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, kl, ij, 2, 2, 0, 0, 2, r_bohr) * ev * tore_b;
            // <D+ P+ | S S>
            kl = INDEXD[5][2];
            core[7][0] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, kl, ij, 2, 1, 0, 0, 2, r_bohr) * ev * tore_b;
            // <D+ D+ | S S>
            kl = INDEXD[5][5];
            core[8][0] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, kl, ij, 2, 2, 0, 0, 2, r_bohr) * ev * tore_b;
            // <D# D# | S S>
            kl = INDEXD[7][7];
            core[9][0] =
                -rijkl(po_a, ddp_a, po_b, ddp_b, kl, ij, 2, 2, 0, 0, 2, r_bohr) * ev * tore_b;
        }
    }
}

/// First transformation step of two-center two-electron integrals.
/// Direct port of OpenMOPAC `tx` (`mndod.F90` lines 1870-1989).
pub fn tx(
    norb_a: usize,
    norb_b: usize,
    rep: &[f64; 492],
    logv: &mut [[bool; 45]; 45],
    v: &mut [[f64; 45]; 45],
    rot: &DOrbitalRotation3D,
) {
    let limkl = INDX[norb_b - 1][norb_b - 1];
    for row in logv.iter_mut() {
        row[..limkl].fill(false);
    }
    for row in v.iter_mut() {
        row[..limkl].fill(0.0);
    }

    for i1 in 1..=norb_a {
        for j1 in 1..=i1 {
            let ij = INDEXD[i1 - 1][j1 - 1];

            for k1 in 1..=norb_b {
                for l1 in 1..=k1 {
                    let kl = INDEXD[k1 - 1][l1 - 1];
                    let nd = IND2[ij - 1][kl - 1];
                    if nd == 0 {
                        continue;
                    }
                    let wrepp = rep[nd];
                    let ll = INDX[k1 - 1][l1 - 1];
                    let mm = MET[ll - 1];

                    match mm {
                        1 => {
                            v[ij - 1][0] = wrepp;
                        }
                        2 => {
                            let k = k1 - 2;
                            v[ij - 1][1] += rot.sp[k][0] * wrepp;
                            v[ij - 1][3] += rot.sp[k][1] * wrepp;
                            v[ij - 1][6] += rot.sp[k][2] * wrepp;
                        }
                        3 => {
                            let k = k1 - 2;
                            let l = l1 - 2;
                            v[ij - 1][2] += rot.pp[0][k][l] * wrepp;
                            v[ij - 1][5] += rot.pp[1][k][l] * wrepp;
                            v[ij - 1][9] += rot.pp[2][k][l] * wrepp;
                            v[ij - 1][4] += rot.pp[3][k][l] * wrepp;
                            v[ij - 1][7] += rot.pp[4][k][l] * wrepp;
                            v[ij - 1][8] += rot.pp[5][k][l] * wrepp;
                        }
                        4 => {
                            let k = k1 - 5;
                            v[ij - 1][10] += rot.sd[k][0] * wrepp;
                            v[ij - 1][15] += rot.sd[k][1] * wrepp;
                            v[ij - 1][21] += rot.sd[k][2] * wrepp;
                            v[ij - 1][28] += rot.sd[k][3] * wrepp;
                            v[ij - 1][36] += rot.sd[k][4] * wrepp;
                        }
                        5 => {
                            let k = k1 - 5;
                            let l = l1 - 2;
                            v[ij - 1][11] += rot.dp[0][k][l] * wrepp;
                            v[ij - 1][12] += rot.dp[1][k][l] * wrepp;
                            v[ij - 1][13] += rot.dp[2][k][l] * wrepp;
                            v[ij - 1][16] += rot.dp[3][k][l] * wrepp;
                            v[ij - 1][17] += rot.dp[4][k][l] * wrepp;
                            v[ij - 1][18] += rot.dp[5][k][l] * wrepp;
                            v[ij - 1][22] += rot.dp[6][k][l] * wrepp;
                            v[ij - 1][23] += rot.dp[7][k][l] * wrepp;
                            v[ij - 1][24] += rot.dp[8][k][l] * wrepp;
                            v[ij - 1][29] += rot.dp[9][k][l] * wrepp;
                            v[ij - 1][30] += rot.dp[10][k][l] * wrepp;
                            v[ij - 1][31] += rot.dp[11][k][l] * wrepp;
                            v[ij - 1][37] += rot.dp[12][k][l] * wrepp;
                            v[ij - 1][38] += rot.dp[13][k][l] * wrepp;
                            v[ij - 1][39] += rot.dp[14][k][l] * wrepp;
                        }
                        6 => {
                            let k = k1 - 5;
                            let l = l1 - 5;
                            v[ij - 1][14] += rot.d_d[0][k][l] * wrepp;
                            v[ij - 1][20] += rot.d_d[1][k][l] * wrepp;
                            v[ij - 1][27] += rot.d_d[2][k][l] * wrepp;
                            v[ij - 1][35] += rot.d_d[3][k][l] * wrepp;
                            v[ij - 1][44] += rot.d_d[4][k][l] * wrepp;
                            v[ij - 1][19] += rot.d_d[5][k][l] * wrepp;
                            v[ij - 1][25] += rot.d_d[6][k][l] * wrepp;
                            v[ij - 1][26] += rot.d_d[7][k][l] * wrepp;
                            v[ij - 1][32] += rot.d_d[8][k][l] * wrepp;
                            v[ij - 1][33] += rot.d_d[9][k][l] * wrepp;
                            v[ij - 1][34] += rot.d_d[10][k][l] * wrepp;
                            v[ij - 1][40] += rot.d_d[11][k][l] * wrepp;
                            v[ij - 1][41] += rot.d_d[12][k][l] * wrepp;
                            v[ij - 1][42] += rot.d_d[13][k][l] * wrepp;
                            v[ij - 1][43] += rot.d_d[14][k][l] * wrepp;
                        }
                        _ => {}
                    }
                }
            }
            for kl in 0..limkl {
                if v[ij - 1][kl].abs() > 1.0e-15 {
                    logv[ij - 1][kl] = true;
                }
            }
        }
    }
}

/// Second transformation step of two-center two-electron integrals.
/// Rotates first center from `v` into `ww: [f64; 2025]`.
/// Direct port of OpenMOPAC `rotatd` (`mndod.F90` lines 1183-1350).
pub fn rotatd_step2(
    norb_a: usize,
    norb_b: usize,
    v: &[[f64; 45]; 45],
    logv: &[[bool; 45]; 45],
    rot: &DOrbitalRotation3D,
    ww: &mut [f64; 2025],
) {
    let limkl = INDX[norb_b - 1][norb_b - 1];
    let limij = INDX[norb_a - 1][norb_a - 1];
    ww[..limij * limkl].fill(0.0);

    for i1 in 1..=norb_a {
        for j1 in 1..=i1 {
            let ij = INDEXD[i1 - 1][j1 - 1];
            let jj = INDX[i1 - 1][j1 - 1];
            let mm = MET[jj - 1];

            for k in 1..=norb_b {
                for l in 1..=k {
                    let kl = INDX[k - 1][l - 1];
                    if !logv[ij - 1][kl - 1] {
                        continue;
                    }
                    let wrepp = v[ij - 1][kl - 1];

                    let indw = |i_orb: usize, j_orb: usize| -> usize {
                        (INDX[i_orb - 1][j_orb - 1] - 1) * limkl + (kl - 1)
                    };

                    match mm {
                        1 => {
                            let iw = indw(1, 1);
                            ww[iw] = wrepp;
                        }
                        2 => {
                            for i in 1..=3 {
                                let iw = indw(i + 1, 1);
                                ww[iw] += rot.sp[i1 - 2][i - 1] * wrepp;
                            }
                        }
                        3 => {
                            for i in 1..=3 {
                                let cc = rot.pp[0][i1 - 2][j1 - 2];
                                let iw = indw(i + 1, i + 1);
                                ww[iw] += cc * wrepp;
                                let iminus = i - 1;
                                if iminus == 0 {
                                    continue;
                                }
                                for j in 1..=iminus {
                                    let cc = rot.pp[i + j][i1 - 2][j1 - 2];
                                    let iw = indw(i + 1, j + 1);
                                    ww[iw] += cc * wrepp;
                                }
                            }
                        }
                        4 => {
                            for i in 1..=5 {
                                let iw = indw(i + 4, 1);
                                ww[iw] += rot.sd[i1 - 5][i - 1] * wrepp;
                            }
                        }
                        5 => {
                            for i in 1..=5 {
                                for j in 1..=3 {
                                    let iw = indw(i + 4, j + 1);
                                    let ij1 = 3 * (i - 1) + j;
                                    ww[iw] += rot.dp[ij1 - 1][i1 - 5][j1 - 2] * wrepp;
                                }
                            }
                        }
                        6 => {
                            for i in 1..=5 {
                                let cc = rot.d_d[i - 1][i1 - 5][j1 - 5];
                                let iw = indw(i + 4, i + 4);
                                ww[iw] += cc * wrepp;
                                let iminus = i - 1;
                                if iminus == 0 {
                                    continue;
                                }
                                for j in 1..=iminus {
                                    let ij1 = INDDD[i - 1][j - 1];
                                    let cc = rot.d_d[ij1 - 1][i1 - 5][j1 - 5];
                                    let iw = indw(i + 4, j + 4);
                                    ww[iw] += cc * wrepp;
                                }
                            }
                        }
                        _ => {}
                    }
                }
            }
        }
    }
}

/// Apply PM7 specific d-orbital coulomb corrections to ww and cored.
/// Direct port of OpenMOPAC `rotatd` lines 1264-1350.
pub fn apply_pm7_d_correction(
    norb_a: usize,
    norb_b: usize,
    has_d_a: bool,
    has_d_b: bool,
    ww: &mut [f64; 2025],
    cored: &mut [[f64; 2]; 10],
) {
    let k_stride = INDX[norb_b - 1][norb_b - 1];

    if has_d_a {
        if norb_b > 1 {
            let mut sum = 0.0;
            for i in 5..=9 {
                let j = k_stride * ((i * (i + 1)) / 2 - 1);
                sum += ww[j + 2] + ww[j + 5] + ww[j + 9];
            }
            sum = ww[0] - sum / 15.0;
            for i in 5..=9 {
                let j = k_stride * ((i * (i + 1)) / 2 - 1);
                for l in 2..=4 {
                    let idx = (l * (l + 1)) / 2 + j - 1;
                    ww[idx] += sum;
                }
            }
            let sum_core = cored[0][0] - (cored[2][0] + 2.0 * cored[3][0]) / 3.0;
            cored[2][0] += sum_core;
            cored[3][0] += sum_core;
        }

        let mut sum = 0.0;
        for i in 5..=9 {
            sum += ww[k_stride * ((i * (i + 1)) / 2 - 1)];
        }
        sum = ww[0] - sum / 5.0;
        for i in 5..=9 {
            let idx = k_stride * ((i * (i + 1)) / 2 - 1);
            ww[idx] += sum;
        }
        let sum_core = cored[0][0] - (cored[6][0] + 2.0 * cored[8][0] + 2.0 * cored[9][0]) / 5.0;
        cored[6][0] += sum_core;
        cored[8][0] += sum_core;
        cored[9][0] += sum_core;
    }

    if has_d_b {
        if has_d_a {
            let mut sum = 0.0;
            for i in 5..=9 {
                let j = 45 * ((i * (i + 1)) / 2 - 1);
                sum += ww[j + 14] + ww[j + 20] + ww[j + 27] + ww[j + 35] + ww[j + 44];
            }
            sum = ww[0] - sum / 25.0;
            for i in 5..=9 {
                let j = 45 * ((i * (i + 1)) / 2 - 1);
                for k in 5..=9 {
                    let idx = (k * (k + 1)) / 2 + j - 1;
                    ww[idx] += sum;
                }
            }
        }
        if norb_a > 1 {
            let mut sum = 0.0;
            for i in 2..=4 {
                let j = 45 * ((i * (i + 1)) / 2 - 1);
                sum += ww[j + 14] + ww[j + 20] + ww[j + 27] + ww[j + 35] + ww[j + 44];
            }
            sum = ww[0] - sum / 15.0;
            for i in 2..=4 {
                let j = 45 * ((i * (i + 1)) / 2 - 1);
                for k in 5..=9 {
                    let idx = (k * (k + 1)) / 2 + j - 1;
                    ww[idx] += sum;
                }
            }
            let sum_core = cored[0][1] - (cored[2][1] + 2.0 * cored[3][1]) / 3.0;
            cored[2][1] += sum_core;
            cored[3][1] += sum_core;
        }
        let sum = ww[0] - (ww[14] + ww[20] + ww[27] + ww[35] + ww[44]) / 5.0;
        for k in 5..=9 {
            let idx = (k * (k + 1)) / 2 - 1;
            ww[idx] += sum;
        }
        let sum_core = cored[0][1] - (cored[6][1] + 2.0 * cored[8][1] + 2.0 * cored[9][1]) / 5.0;
        cored[6][1] += sum_core;
        cored[8][1] += sum_core;
        cored[9][1] += sum_core;
    }
}

/// Accumulate nuclear stabilization terms `elenuc` into one-electron matrix `h` for atom pair A and B.
/// Direct port of OpenMOPAC `elenuc` (`mndod.F90` lines 2367-2488).
pub fn accumulate_elenuc_block(
    norb_a: usize,
    norb_b: usize,
    orb_start_a: usize,
    orb_start_b: usize,
    cored: &[[f64; 2]; 10],
    rot: &DOrbitalRotation3D,
    h: &mut crate::types::AlignedMatrix<f64>,
) {
    // Atom A: center n=0
    for i in 0..norb_a {
        for j in 0..=i {
            let val = if i == 0 && j == 0 {
                cored[0][0]
            } else if i < 4 && j == 0 {
                rot.sp[0][i - 1] * cored[1][0]
            } else if i < 4 && j < 4 {
                let ipp = INDPP[i - 1][j - 1] - 1;
                cored[2][0] * rot.pp[ipp][0][0]
                    + cored[3][0] * (rot.pp[ipp][1][1] + rot.pp[ipp][2][2])
            } else if i >= 4 && j == 0 {
                rot.sd[0][i - 4] * cored[4][0]
            } else if i >= 4 && j < 4 {
                let idp = INDDP[i - 4][j - 1] - 1;
                cored[5][0] * rot.dp[idp][0][0]
                    + cored[7][0] * (rot.dp[idp][1][1] + rot.dp[idp][2][2])
            } else {
                let idd = INDDD[i - 4][j - 4] - 1;
                cored[6][0] * rot.d_d[idd][0][0]
                    + cored[8][0] * (rot.d_d[idd][1][1] + rot.d_d[idd][2][2])
                    + cored[9][0] * (rot.d_d[idd][3][3] + rot.d_d[idd][4][4])
            };
            let idx_i = orb_start_a + i;
            let idx_j = orb_start_a + j;
            let cur = h.get(idx_i, idx_j);
            h.set(idx_i, idx_j, cur + val);
            if i != j {
                h.set(idx_j, idx_i, cur + val);
            }
        }
    }

    // Atom B: center n=1
    for i in 0..norb_b {
        for j in 0..=i {
            let val = if i == 0 && j == 0 {
                cored[0][1]
            } else if i < 4 && j == 0 {
                rot.sp[0][i - 1] * cored[1][1]
            } else if i < 4 && j < 4 {
                let ipp = INDPP[i - 1][j - 1] - 1;
                cored[2][1] * rot.pp[ipp][0][0]
                    + cored[3][1] * (rot.pp[ipp][1][1] + rot.pp[ipp][2][2])
            } else if i >= 4 && j == 0 {
                rot.sd[0][i - 4] * cored[4][1]
            } else if i >= 4 && j < 4 {
                let idp = INDDP[i - 4][j - 1] - 1;
                cored[5][1] * rot.dp[idp][0][0]
                    + cored[7][1] * (rot.dp[idp][1][1] + rot.dp[idp][2][2])
            } else {
                let idd = INDDD[i - 4][j - 4] - 1;
                cored[6][1] * rot.d_d[idd][0][0]
                    + cored[8][1] * (rot.d_d[idd][1][1] + rot.d_d[idd][2][2])
                    + cored[9][1] * (rot.d_d[idd][3][3] + rot.d_d[idd][4][4])
            };
            let idx_i = orb_start_b + i;
            let idx_j = orb_start_b + j;
            let cur = h.get(idx_i, idx_j);
            h.set(idx_i, idx_j, cur + val);
            if i != j {
                h.set(idx_j, idx_i, cur + val);
            }
        }
    }
}

